"""Print-ready STLs from the AUTHORITATIVE FreeCAD model (#72): opens puck.FCStd, applies the print
orientation of each printed part (same table as PRINTING.md / cad/print_export.py), sits it on z = 0
centred on x = y = 0, and writes ../exports/print/<part>.stl. The tolerance coupon is a test artefact,
not product geometry, and stays generated by cad/print_export.py.
Run: freecadcmd -c "exec(open('print_fc.py').read())"  (or user-freecad execute_code_headless)
"""
import os
import FreeCAD as App
import Mesh

HERE = os.environ.get("TK_FC_DIR") or os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "exports", "print")
ORIENT = {"top_shell": None, "bottom_tray": None, "hatch_cover": None, "knob": ((1, 0, 0), 180),
          "button_cap_btn1": None, "button_cap_btn2": None, "light_pipe": None}
os.makedirs(OUT, exist_ok=True)
doc = App.openDocument(os.path.join(HERE, "puck.FCStd"))
for k, rot in ORIENT.items():
    s = doc.getObject(k).Shape.copy()
    if rot:
        bb = s.BoundBox
        s.rotate(bb.Center, App.Vector(*rot[0]), rot[1])
    bb = s.optimalBoundingBox()
    s.translate(App.Vector(-(bb.XMin + bb.XMax) / 2, -(bb.YMin + bb.YMax) / 2, -bb.ZMin))
    m = Mesh.Mesh()
    m.addFacets(s.tessellate(0.01))
    m.write(os.path.join(OUT, f"{k}.stl"))
    print("wrote", k)
App.closeDocument(doc.Name)
